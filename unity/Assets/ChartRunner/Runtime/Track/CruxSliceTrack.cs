using UnityEngine;

namespace ChartRunner.Track
{
    /// <summary>
    /// Рукотворный отрезок на ~30 секунд с намеренными точками выбора.
    ///
    /// ПОЧЕМУ ОН ПОНАДОБИЛСЯ И ПОЧЕМУ ИМЕННО ТАКОЙ КРУТИЗНЫ. Дизайн-трасса `VS` перенесена
    /// 1:1 и содержит узлы 45.0°, 47.7°, а по интерполяции доходит до 50.8°. Автор исходника
    /// измерил предел собственной игры и записал его прямо в код (chartrider.html:654):
    ///
    ///     climbSteep 25 (пик ~54°) = НЕПРОЕЗЖАЕМАЯ СТЕНА (сток вязнет/катится назад даже
    ///     с разгоном, climbGrip не тянет; сим-подтверждено). 15 (пик ~41°, ср ~30°) = сток
    ///     ЕДВА вылезает (крукс: надо ВЕЗТИ скорость)
    ///
    /// То есть проходимость держится на узком коридоре, и `VS` из него вышла: замерено, что
    /// байк встаёт на 271 м (86 % трассы) при уклоне 50.8°, и туда упираются ВСЕ политики
    /// пилота — и «зажал газ», и все 18 вариантов дозировки. Пока стена там, любой замер
    /// навыка меряет её положение (docs/skill-policy-comparison.md).
    ///
    /// Здесь крутизна взята по калибровке автора: пик 40.2° по хордам узлов, средний подъём
    /// около 30°. Цель не «сделать полегче», а попасть в тот коридор, где, по его же замеру,
    /// сток ЕДВА вылезает — то есть где решает везомая скорость и дозировка, а не наличие
    /// физической возможности.
    ///
    /// ТОЧКИ ВЫБОРА расставлены намеренно, а не «чтобы было интересно»:
    ///   1. подъём 36.9° сразу после разгона — учит, что газ задирает нос;
    ///   2. спуск 36.6° — единственное место, где набирается скорость под второй подъём;
    ///   3. КРУКС: подъём 40.2° длиной 25 м — пройти можно только привезя скорость со спуска,
    ///      и полный газ здесь задирает нос раньше, чем кончается подъём;
    ///   4. спуск 40.6° с выходом на площадку — проверка приземления, а не подъёма.
    ///
    /// Приёмка отрезка одна и она falsifiable: «только газ» обязан проваливаться, дозировка
    /// обязана проходить. Мерится в CruxSliceAcceptance.
    /// </summary>
    public static class CruxSliceTrack
    {
        /// <summary>Узлы в авторских px, высота вверх = +. Те же единицы, что у VS.</summary>
        public static Vector2[] Nodes =>
            new[]
            {
                new Vector2(0, 0), new Vector2(700, 0),          // 0,1 разгон, 20 м
                new Vector2(1400, 120),                          // 2  пологий вход, 9.7°
                new Vector2(2200, 720),                          // 3  подъём 36.9° — учит без наказания
                new Vector2(2500, 800),                          // 4  вершина, 14.9°
                new Vector2(3200, 280),                          // 5  спуск 36.6° — здесь берётся скорость
                new Vector2(3450, 240),                          // 6  подвод к кикеру
                new Vector2(3600, 370),                          // 7  КИКЕР, кромка ОСТРАЯ, 40.9°
                new Vector2(3900, 280),                          // 8  зона приземления
                new Vector2(4900, 1100),                         // 9  КРУКС: подъём 39.4°, 28 м
                new Vector2(5200, 1160),                         // 10 вершина, 11.3°
                new Vector2(5900, 580),                          // 11 спуск 39.6°
                new Vector2(6500, 580)                           // 12 выкат и финиш
            };

        public const float EndPx = 6500f;
        public const float NodeStepPx = 26f;

        public static TrackProfile CreateProfile()
        {
            var t = ScriptableObject.CreateInstance<TrackProfile>();
            t.name = "CruxSlice";
            t.nodesPx = Nodes;
            t.gapsPx = new TrackProfile.Gap[0];
            // Кромка кикера НЕ сглаживается: монотонная кубика гасит касательные в нуль на
            // любом локальном максимуме, и острый лип в этом формате иначе не выразить.
            // Без этого кикер превращается в пологий бугор и перестаёт быть точкой выбора.
            t.sharpNodeIndices = new[] { 7 };
            t.endPx = EndPx;
            t.nodeStepPx = NodeStepPx;
            // Чекпоинты стоят ПОСЛЕ каждой точки выбора, а не перед: смысл рестарта в том,
            // чтобы повторять нерешённое место, а не переезжать заново уже освоенное.
            t.checkpoints = new[]
            {
                new TrackProfile.Checkpoint { xPx = 2600f, name = "после первого подъёма" },
                new TrackProfile.Checkpoint { xPx = 3250f, name = "перед кикером" },
                new TrackProfile.Checkpoint { xPx = 5250f, name = "после крукса" }
            };
            t.flowBoostEnabled = false;
            return t;
        }
    }
}
