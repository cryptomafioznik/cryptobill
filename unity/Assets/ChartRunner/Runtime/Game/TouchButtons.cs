using UnityEngine;

namespace ChartRunner.Game
{
    /// <summary>
    /// Схема управления `btn4` — ЧЕТЫРЕ КНОПКИ, перенесённая из toys/chartrider.html.
    ///
    /// ПОЧЕМУ ИМЕННО ОНА, А НЕ МОЯ. В исходнике записано прямым текстом:
    ///
    ///     let ctrlScheme='btn4';   // b56: 4 КНОПКИ = ДЕФОЛТ (юзер выбрал — удобнее)
    ///
    /// То есть схема уже была выбрана пользователем среди четырёх (жесты, авто-газ,
    /// 4 кнопки, гироскоп) и зафиксирована как дефолт. Я вместо переноса выдумал своё —
    /// «правая половина газ, левая тормоз, вертикальный драг = вес», — и получил ровно
    /// то, что должен был: «управление очень неудобное, старое было намного удобнее».
    /// Это тот же класс ошибки, что и с потерянной константой: решение уже принято и
    /// записано, а я решил заново.
    ///
    /// РАСКЛАДКА перенесена по координатам исходника (стр. 4451-4458), в его же единицах
    /// (кадр 430 × 932 логических точек), поэтому пропорции и зоны попадания совпадают:
    ///   ГАЗ    справа снизу, 116 × 62, низ на 110 от края
    ///   ТОРМОЗ над газом,    116 × 60, низ на 178
    ///   НОС↑   слева снизу,   84 × 62 — вес НАЗАД, вилли
    ///   НОС↓   рядом с ним,   84 × 62 — вес ВПЕРЁД
    ///
    /// ПРЫЖОК и ПАМП исходника здесь не рисуются: прыжок в профиле по умолчанию выключен,
    /// памп не портирован. Рисовать кнопку, которая ничего не делает, хуже, чем её не иметь.
    ///
    /// НАКЛОН ОТ КНОПОК НЕ ДИСКРЕТНЫЙ. Аудит §6.9 справедливо ругал исходник за мгновенный
    /// ±1, но чинить это сменой схемы не нужно: рампа переноса веса 0.55 с живёт в физике
    /// (BikeController.ApplyWeightShift), поэтому удержание кнопки даёт плавно нарастающий
    /// вес. Кнопки удобные, а вес аналоговый.
    /// </summary>
    public class TouchButtons
    {
        /// <summary>Опорный кадр, в котором заданы координаты. Совпадает с исходником.</summary>
        public const float RefW = 430f;
        public const float RefH = 932f;

        public struct Zone
        {
            public Rect R;
            public string Label;
            public bool Active;
        }

        public Zone Gas;
        public Zone Brake;
        public Zone NoseUp;
        public Zone NoseDown;

        public TouchButtons()
        {
            const float bw = 116f, lw = 84f;
            var gx = RefW - 14f - bw;

            Gas = new Zone { R = new Rect(gx, RefH - 110f, bw, 62f), Label = "ГАЗ" };
            Brake = new Zone { R = new Rect(gx, RefH - 178f, bw, 60f), Label = "ТОРМОЗ" };
            NoseUp = new Zone { R = new Rect(14f, RefH - 110f, lw, 62f), Label = "НОС↑" };
            NoseDown = new Zone { R = new Rect(14f + lw + 6f, RefH - 110f, lw, 62f), Label = "НОС↓" };
        }

        /// <summary>
        /// Попадание пальца. Координаты касания приходят в ПИКСЕЛЯХ экрана, кнопки заданы
        /// в опорном кадре — перевод здесь, в одном месте, иначе на разных устройствах
        /// зоны попадания разъедутся с нарисованными.
        ///
        /// Начало координат тача у Unity внизу слева, у GUI — вверху слева. Перепутать
        /// это — значит получить кнопки, которые видно вверху, а нажимаются внизу.
        /// </summary>
        public static bool Hit(Rect refRect, Vector2 touchPx)
        {
            var sx = Screen.width / RefW;
            var sy = Screen.height / RefH;
            var guiY = Screen.height - touchPx.y;
            var r = new Rect(refRect.x * sx, refRect.y * sy, refRect.width * sx, refRect.height * sy);
            // Расширение зоны попадания на 8 опорных точек по кругу: палец толще пикселя,
            // и промах по краю кнопки читается как «управление не работает».
            r.xMin -= 8f * sx; r.xMax += 8f * sx;
            r.yMin -= 8f * sy; r.yMax += 8f * sy;
            return r.Contains(new Vector2(touchPx.x, guiY));
        }
    }
}
